#!/usr/bin/env bash
# Usage: finish-repo.sh OWNER/REPO OVERLAY public|private --license SPDX|none
#          [--addon api-http|api-events]... [--desc TEXT]
# Finishes a repository that was created from OWNER/repo-template in the
# GitHub UI (the template repo is a reference copy: it cannot pick an overlay,
# fill placeholders, choose a license or apply settings). It:
#   1. clones the repo and applies the overlay, add-ons and placeholders;
#   2. sets the chosen license and generates lock files;
#   3. applies the repository settings and ruleset;
#   4. opens a "chore: finish repo-standard setup" PR (never pushes to main).
# shellcheck source=lib.sh
source "$(dirname "$0")/lib.sh"

full="${1:?owner/repo}"; overlay="${2:?overlay}"; vis="${3:?public|private}"; shift 3
owner="${full%%/*}"; name="${full#*/}"
license=""; desc="$name"; addons=()
while [ $# -gt 0 ]; do
  case "$1" in
    --license) license="$2"; shift ;;
    --addon) addons+=("$2"); shift ;;
    --desc) desc="$2"; shift ;;
    *) die "unknown option $1" ;;
  esac
  shift
done
load_owner "$owner"
[ -n "$license" ] || die "--license is required (an SPDX id such as apache-2.0 or mit, or none)"
case "$vis" in public|private) ;; *) die "visibility must be public or private" ;; esac
work="$(mktemp -d)"; trap 'rm -rf "$work"' EXIT
dir="$work/$name"

gh_as "$owner" repo clone "$full" "$dir" -- -q
set_identity "$dir" "$owner"
git -C "$dir" switch -q -c chore/finish-repo-standard
# Undo the template repo's stand-in text so the normal placeholders apply.
perl -pi -e 's/One-paragraph description of this project\./__DESCRIPTION__/g' "$dir/README.md"
perl -pi -e 's/this project/__REPO_NAME__/g' "$dir/docs/index.md" "$dir/docs/dev/index.md"
pub_flag=(); [ "$vis" = public ] && pub_flag=(--public)
"$STANDARD_ROOT/scripts/apply-overlay.sh" "$dir" "$overlay" ${pub_flag[@]+"${pub_flag[@]}"} \
  --owner "$owner" --name "$name" --desc "$desc"
for addon in ${addons[@]+"${addons[@]}"}; do
  "$STANDARD_ROOT/scripts/apply-overlay.sh" "$dir" "$addon" --owner "$owner" --name "$name" --desc "$desc"
done
write_license "$dir" "$owner" "$license"
make_locks "$dir" "$overlay"

"$STANDARD_ROOT/scripts/apply-settings.sh" "$full" "$vis"
git -C "$dir" add -A
git -C "$dir" commit -q -m "chore: finish repo-standard setup" \
  -m "Applies the $overlay overlay, license and placeholders to a repo created from repo-template."
git -C "$dir" push -q -u origin chore/finish-repo-standard
gh_as "$owner" pr create --repo "$full" --head chore/finish-repo-standard \
  --title "chore: finish repo-standard setup" \
  --body "Generated by repo-standard scripts/finish-repo.sh. Review the diff, then squash-merge."
